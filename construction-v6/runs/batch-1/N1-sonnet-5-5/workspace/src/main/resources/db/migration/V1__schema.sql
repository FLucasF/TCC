CREATE TABLE products (
    sku          VARCHAR(64)    PRIMARY KEY,
    name         VARCHAR(255)   NOT NULL,
    price        NUMERIC(12, 2) NOT NULL,
    weight_kg    NUMERIC(10, 2) NOT NULL,
    stock        INTEGER        NOT NULL CHECK (stock >= 0),
    discontinued BOOLEAN        NOT NULL
);

CREATE TABLE customers (
    cpf            VARCHAR(255)   PRIMARY KEY,
    credit_balance NUMERIC(12, 2) NOT NULL
);

CREATE TABLE orders (
    id            VARCHAR(36)              PRIMARY KEY,
    cpf           VARCHAR(255)             NOT NULL REFERENCES customers (cpf),
    email         VARCHAR(255)             NOT NULL,
    status        VARCHAR(32)              NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    tracking_code VARCHAR(255),
    summary_json  TEXT                     NOT NULL
);
CREATE INDEX idx_orders_cpf ON orders (cpf, status);

CREATE TABLE order_items (
    order_id VARCHAR(36)  NOT NULL REFERENCES orders (id),
    sku      VARCHAR(64)  NOT NULL,
    quantity INTEGER      NOT NULL,
    position INTEGER      NOT NULL,
    PRIMARY KEY (order_id, sku)
);

CREATE TABLE payment_notices (
    order_id       VARCHAR(36)  NOT NULL REFERENCES orders (id),
    transaction_id VARCHAR(255) NOT NULL,
    error_code     VARCHAR(64),
    PRIMARY KEY (order_id, transaction_id)
);

CREATE TABLE notifications (
    seq      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id       VARCHAR(36)  NOT NULL UNIQUE,
    cpf      VARCHAR(255) NOT NULL REFERENCES customers (cpf),
    type     VARCHAR(32)  NOT NULL,
    order_id VARCHAR(36)  NOT NULL,
    status   VARCHAR(8)   NOT NULL
);
CREATE INDEX idx_notifications_cpf ON notifications (cpf, seq);
