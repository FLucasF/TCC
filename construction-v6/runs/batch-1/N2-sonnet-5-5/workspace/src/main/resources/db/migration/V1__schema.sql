CREATE TABLE products (
    sku           VARCHAR(40)   PRIMARY KEY,
    name          VARCHAR(200)  NOT NULL,
    price         NUMERIC(12,2) NOT NULL,
    weight_kg     NUMERIC(10,3) NOT NULL,
    stock         INTEGER       NOT NULL CHECK (stock >= 0),
    discontinued  BOOLEAN       NOT NULL
);

CREATE TABLE customers (
    cpf             VARCHAR(11)   PRIMARY KEY,
    email           VARCHAR(320)  NOT NULL,
    credit_balance  NUMERIC(12,2) NOT NULL DEFAULT 0
);

CREATE TABLE orders (
    id                      VARCHAR(36)   PRIMARY KEY,
    customer_cpf            VARCHAR(11)   NOT NULL REFERENCES customers (cpf),
    status                  VARCHAR(20)   NOT NULL,
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    tracking_code           VARCHAR(100),
    payment_transaction_id  VARCHAR(100),
    payment_outcome         VARCHAR(40),
    products_subtotal       NUMERIC(12,2) NOT NULL,
    coupon_discount         NUMERIC(12,2) NOT NULL,
    shipping_cost           NUMERIC(12,2) NOT NULL,
    delivery_days           INTEGER       NOT NULL,
    insurance               NUMERIC(12,2) NOT NULL,
    payment_adjustment      NUMERIC(12,2) NOT NULL,
    final_total             NUMERIC(12,2) NOT NULL,
    installments            INTEGER       NOT NULL,
    installment_amount      NUMERIC(12,2) NOT NULL,
    next_purchase_credit    NUMERIC(12,2) NOT NULL,
    gift                    BOOLEAN       NOT NULL
);

CREATE INDEX idx_orders_customer ON orders (customer_cpf);

CREATE TABLE order_items (
    order_id  VARCHAR(36) NOT NULL REFERENCES orders (id),
    line_no   INTEGER     NOT NULL,
    sku       VARCHAR(40) NOT NULL REFERENCES products (sku),
    quantity  INTEGER     NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (order_id, line_no)
);

CREATE TABLE notifications (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_cpf  VARCHAR(11) NOT NULL REFERENCES customers (cpf),
    type          VARCHAR(30) NOT NULL,
    order_id      VARCHAR(36) NOT NULL,
    status        VARCHAR(10) NOT NULL
);

CREATE INDEX idx_notifications_customer ON notifications (customer_cpf);

