CREATE TABLE IF NOT EXISTS produto (
    sku           VARCHAR(40)    PRIMARY KEY,
    nome          VARCHAR(200)   NOT NULL,
    preco         NUMERIC(12, 2) NOT NULL,
    peso_kg       NUMERIC(10, 3) NOT NULL,
    estoque       INTEGER        NOT NULL CHECK (estoque >= 0),
    fora_de_linha BOOLEAN        NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
    cpf            VARCHAR(11)    PRIMARY KEY,
    email          VARCHAR(320)   NOT NULL,
    saldo_credito  NUMERIC(12, 2) NOT NULL
);

CREATE TABLE IF NOT EXISTS pedido (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf                VARCHAR(11)              NOT NULL REFERENCES cliente (cpf),
    situacao           VARCHAR(40)              NOT NULL,
    criado_em          TIMESTAMP WITH TIME ZONE NOT NULL,
    resumo             TEXT                     NOT NULL,
    codigo_rastreio    VARCHAR(100),
    id_transacao       VARCHAR(200),
    pago_em            TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS pedido_cpf ON pedido (cpf);

CREATE TABLE IF NOT EXISTS item_pedido (
    pedido_id  BIGINT      NOT NULL REFERENCES pedido (id),
    sku        VARCHAR(40) NOT NULL REFERENCES produto (sku),
    quantidade INTEGER     NOT NULL,
    posicao    INTEGER     NOT NULL,
    PRIMARY KEY (pedido_id, sku)
);

CREATE TABLE IF NOT EXISTS aviso (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf        VARCHAR(11) NOT NULL REFERENCES cliente (cpf),
    tipo       VARCHAR(40) NOT NULL,
    pedido_id  BIGINT      NOT NULL REFERENCES pedido (id),
    situacao   VARCHAR(10) NOT NULL
);

CREATE INDEX IF NOT EXISTS aviso_cpf ON aviso (cpf);
