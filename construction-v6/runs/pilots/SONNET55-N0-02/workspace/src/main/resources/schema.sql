CREATE TABLE IF NOT EXISTS produto (
    sku           VARCHAR(50)    PRIMARY KEY,
    nome          VARCHAR(200)   NOT NULL,
    preco         NUMERIC(12, 2) NOT NULL,
    peso_kg       NUMERIC(10, 3) NOT NULL,
    estoque       INTEGER        NOT NULL CHECK (estoque >= 0),
    fora_de_linha BOOLEAN        NOT NULL
);

CREATE TABLE IF NOT EXISTS cliente (
    cpf           VARCHAR(20)    PRIMARY KEY,
    email         VARCHAR(200)   NOT NULL,
    saldo_credito NUMERIC(14, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS pedido (
    id              VARCHAR(50)  PRIMARY KEY,
    cpf             VARCHAR(20)  NOT NULL,
    email           VARCHAR(200) NOT NULL,
    situacao        VARCHAR(30)  NOT NULL,
    criado_em       TIMESTAMP    NOT NULL,
    resumo          TEXT         NOT NULL,
    codigo_rastreio VARCHAR(100),
    id_transacao    VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS idx_pedido_cpf ON pedido (cpf);

CREATE TABLE IF NOT EXISTS pedido_item (
    pedido_id  VARCHAR(50) NOT NULL,
    posicao    INTEGER     NOT NULL,
    sku        VARCHAR(50) NOT NULL,
    quantidade INTEGER     NOT NULL,
    PRIMARY KEY (pedido_id, posicao)
);

CREATE TABLE IF NOT EXISTS aviso (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf       VARCHAR(20)  NOT NULL,
    tipo      VARCHAR(40)  NOT NULL,
    pedido_id VARCHAR(50)  NOT NULL,
    mensagem  VARCHAR(500) NOT NULL,
    situacao  VARCHAR(10)  NOT NULL,
    criado_em TIMESTAMP    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_aviso_cpf ON aviso (cpf);
