CREATE TABLE IF NOT EXISTS produto (
    sku           VARCHAR(64)    PRIMARY KEY,
    nome          VARCHAR        NOT NULL,
    preco         NUMERIC(12, 2) NOT NULL CHECK (preco >= 0),
    peso_kg       NUMERIC(10, 3) NOT NULL CHECK (peso_kg >= 0),
    estoque       INTEGER        NOT NULL CHECK (estoque >= 0),
    fora_de_linha BOOLEAN        NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS cliente (
    cpf           VARCHAR(64)    PRIMARY KEY,
    email         VARCHAR        NOT NULL,
    saldo_credito NUMERIC(14, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS pedido (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf                    VARCHAR(64)              NOT NULL REFERENCES cliente (cpf),
    email                  VARCHAR                  NOT NULL,
    cep                    VARCHAR(8)               NOT NULL,
    regiao                 VARCHAR(32)              NOT NULL,
    modalidade_entrega     VARCHAR(64)              NOT NULL,
    cupom                  VARCHAR(64),
    forma_pagamento        VARCHAR(32)              NOT NULL,
    nivel_clube            VARCHAR(32)              NOT NULL,
    situacao               VARCHAR(32)              NOT NULL,
    criado_em              TIMESTAMP WITH TIME ZONE NOT NULL,
    subtotal_produtos      NUMERIC(14, 2)           NOT NULL,
    desconto_cupom         NUMERIC(14, 2)           NOT NULL,
    frete                  NUMERIC(14, 2)           NOT NULL,
    prazo_entrega_dias     INTEGER                  NOT NULL,
    seguro                 NUMERIC(14, 2)           NOT NULL,
    ajuste_pagamento       NUMERIC(14, 2)           NOT NULL,
    total_final            NUMERIC(14, 2)           NOT NULL,
    parcelas               INTEGER                  NOT NULL,
    valor_parcela          NUMERIC(14, 2)           NOT NULL,
    credito_proxima_compra NUMERIC(14, 2)           NOT NULL,
    brinde                 BOOLEAN                  NOT NULL,
    codigo_rastreio        VARCHAR,
    id_transacao           VARCHAR,
    pago_em                TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_pedido_cpf ON pedido (cpf);

CREATE TABLE IF NOT EXISTS pedido_item (
    pedido_id      BIGINT         NOT NULL REFERENCES pedido (id),
    sku            VARCHAR(64)    NOT NULL REFERENCES produto (sku),
    quantidade     INTEGER        NOT NULL CHECK (quantidade > 0),
    preco_unitario NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (pedido_id, sku)
);

CREATE TABLE IF NOT EXISTS aviso (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cpf       VARCHAR(64)              NOT NULL REFERENCES cliente (cpf),
    pedido_id BIGINT                   NOT NULL REFERENCES pedido (id),
    tipo      VARCHAR(32)              NOT NULL,
    situacao  VARCHAR(16)              NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_aviso_cpf ON aviso (cpf, id);
