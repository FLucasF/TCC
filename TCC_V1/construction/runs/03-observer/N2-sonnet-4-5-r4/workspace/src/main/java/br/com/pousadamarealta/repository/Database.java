package br.com.pousadamarealta.repository;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.SQLException;

public class Database {
    private final DataSource dataSource;

    public Database(DataSource dataSource) {
        this.dataSource = dataSource;
    }

    public Connection getConnection() throws SQLException {
        return dataSource.getConnection();
    }

    public void initialize() {
        try (Connection conn = getConnection()) {
            createTables(conn);
            insertInitialRooms(conn);
        } catch (SQLException e) {
            throw new RuntimeException("Failed to initialize database", e);
        }
    }

    private void createTables(Connection conn) throws SQLException {
        boolean isH2 = conn.getMetaData().getDatabaseProductName().contains("H2");
        String idColumn = isH2 ? "BIGINT GENERATED BY DEFAULT AS IDENTITY" : "BIGSERIAL";

        String createRooms = """
            CREATE TABLE IF NOT EXISTS rooms (
                number VARCHAR(10) PRIMARY KEY,
                type VARCHAR(20) NOT NULL
            )
            """;

        String createReservations = String.format("""
            CREATE TABLE IF NOT EXISTS reservations (
                id %s PRIMARY KEY,
                room_number VARCHAR(10) NOT NULL,
                guest_name VARCHAR(255) NOT NULL,
                guest_email VARCHAR(255) NOT NULL,
                guest_cpf VARCHAR(11) NOT NULL,
                check_in DATE NOT NULL,
                check_out DATE NOT NULL,
                guests INTEGER NOT NULL,
                rate_plan VARCHAR(20) NOT NULL,
                status VARCHAR(20) NOT NULL,
                amount_paid DECIMAL(10, 2) NOT NULL DEFAULT 0,
                refund DECIMAL(10, 2),
                FOREIGN KEY (room_number) REFERENCES rooms(number)
            )
            """, idColumn);

        String createMessages = String.format("""
            CREATE TABLE IF NOT EXISTS messages (
                id %s PRIMARY KEY,
                channel VARCHAR(50) NOT NULL,
                destination VARCHAR(255) NOT NULL,
                subject VARCHAR(500) NOT NULL,
                body TEXT NOT NULL
            )
            """, idColumn);

        conn.createStatement().execute(createRooms);
        conn.createStatement().execute(createReservations);
        conn.createStatement().execute(createMessages);
    }

    private void insertInitialRooms(Connection conn) throws SQLException {
        String checkRooms = "SELECT COUNT(*) FROM rooms";
        var rs = conn.createStatement().executeQuery(checkRooms);
        rs.next();
        if (rs.getInt(1) > 0) {
            return;
        }

        String insertRoom = "INSERT INTO rooms (number, type) VALUES (?, ?)";
        var stmt = conn.prepareStatement(insertRoom);

        String[][] rooms = {
            {"101", "STANDARD"},
            {"102", "STANDARD"},
            {"201", "DELUXE"},
            {"202", "DELUXE"},
            {"301", "SUITE"}
        };

        for (String[] room : rooms) {
            stmt.setString(1, room[0]);
            stmt.setString(2, room[1]);
            stmt.addBatch();
        }

        stmt.executeBatch();
    }
}
