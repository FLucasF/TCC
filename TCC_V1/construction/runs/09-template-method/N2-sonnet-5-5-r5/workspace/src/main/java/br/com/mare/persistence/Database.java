package br.com.mare.persistence;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

import javax.sql.DataSource;

/** Conexão com o banco e criação do que o sistema precisa nele. */
public final class Database {
    private static final int ATTEMPTS = 30;

    private Database() {
    }

    public static DataSource connect(String url, String user, String password) {
        HikariConfig config = new HikariConfig();
        config.setJdbcUrl(url);
        if (user != null) {
            config.setUsername(user);
        }
        if (password != null) {
            config.setPassword(password);
        }
        config.setInitializationFailTimeout(-1);
        HikariDataSource dataSource = new HikariDataSource(config);
        createSchema(dataSource);
        return dataSource;
    }

    static void createSchema(DataSource dataSource) {
        SQLException last = null;
        for (int attempt = 0; attempt < ATTEMPTS; attempt++) {
            try (Connection c = dataSource.getConnection(); Statement s = c.createStatement()) {
                s.execute("""
                        CREATE TABLE IF NOT EXISTS reservations (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            room_number INT NOT NULL,
                            guest_name VARCHAR(255) NOT NULL,
                            guest_email VARCHAR(255) NOT NULL,
                            guest_cpf VARCHAR(50) NOT NULL,
                            check_in DATE NOT NULL,
                            check_out DATE NOT NULL,
                            guests INT NOT NULL,
                            rate_plan VARCHAR(30) NOT NULL,
                            nights INT NOT NULL,
                            subtotal NUMERIC(12,2) NOT NULL,
                            discount NUMERIC(12,2) NOT NULL,
                            total NUMERIC(12,2) NOT NULL,
                            status VARCHAR(30) NOT NULL,
                            amount_paid NUMERIC(12,2) NOT NULL,
                            refund NUMERIC(12,2)
                        )""");
                s.execute("""
                        CREATE TABLE IF NOT EXISTS messages (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            channel VARCHAR(30) NOT NULL,
                            recipient VARCHAR(255) NOT NULL,
                            subject VARCHAR(255) NOT NULL,
                            body TEXT NOT NULL
                        )""");
                return;
            } catch (SQLException e) {
                last = e;
                try {
                    Thread.sleep(1000);
                } catch (InterruptedException ie) {
                    Thread.currentThread().interrupt();
                    break;
                }
            }
        }
        throw new IllegalStateException("Não foi possível preparar o banco", last);
    }
}
