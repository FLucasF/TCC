package pousada.db;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.function.Supplier;

/** Acesso ao banco; dentro de transaction() todas as consultas usam a mesma conexão. */
public class Database {
    public interface SqlFunction<T> {
        T apply(Connection connection) throws SQLException;
    }

    private final String url;
    private final String user;
    private final String password;
    private final ThreadLocal<Connection> current = new ThreadLocal<>();

    public Database(String url, String user, String password) {
        this.url = url;
        this.user = user;
        this.password = password;
    }

    private Connection open() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    public <T> T query(SqlFunction<T> work) {
        Connection shared = current.get();
        try {
            if (shared != null) {
                return work.apply(shared);
            }
            try (Connection connection = open()) {
                return work.apply(connection);
            }
        } catch (SQLException e) {
            throw new IllegalStateException(e);
        }
    }

    public <T> T transaction(Supplier<T> work) {
        if (current.get() != null) {
            return work.get();
        }
        try (Connection connection = open()) {
            connection.setAutoCommit(false);
            current.set(connection);
            try {
                T result = work.get();
                connection.commit();
                return result;
            } catch (RuntimeException e) {
                connection.rollback();
                throw e;
            } finally {
                current.remove();
            }
        } catch (SQLException e) {
            throw new IllegalStateException(e);
        }
    }

    /** Cria o que o sistema precisa num banco vazio; não mexe no que já existe. */
    public void createSchema() {
        query(c -> {
            try (Statement st = c.createStatement()) {
                st.execute("""
                        CREATE TABLE IF NOT EXISTS reservations (
                            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            room_number INTEGER NOT NULL,
                            guest_name VARCHAR(200) NOT NULL,
                            guest_email VARCHAR(200) NOT NULL,
                            guest_cpf VARCHAR(30) NOT NULL,
                            check_in DATE NOT NULL,
                            check_out DATE NOT NULL,
                            guests INTEGER NOT NULL,
                            rate_plan VARCHAR(30) NOT NULL,
                            nights INTEGER NOT NULL,
                            subtotal NUMERIC(12,2) NOT NULL,
                            discount NUMERIC(12,2) NOT NULL,
                            total NUMERIC(12,2) NOT NULL,
                            status VARCHAR(30) NOT NULL,
                            amount_paid NUMERIC(12,2) NOT NULL,
                            refund NUMERIC(12,2)
                        )""");
                st.execute("""
                        CREATE TABLE IF NOT EXISTS messages (
                            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            channel VARCHAR(20) NOT NULL,
                            recipient VARCHAR(200) NOT NULL,
                            subject VARCHAR(500) NOT NULL,
                            body VARCHAR(10000) NOT NULL
                        )""");
            }
            return null;
        });
    }

    /** Espera o banco aceitar conexões (ele pode subir junto com o sistema). */
    public void createSchemaWithRetry(int attempts) {
        for (int i = 1; ; i++) {
            try {
                createSchema();
                return;
            } catch (RuntimeException e) {
                if (i >= attempts) {
                    throw e;
                }
                try {
                    Thread.sleep(1000);
                } catch (InterruptedException ie) {
                    Thread.currentThread().interrupt();
                    throw e;
                }
            }
        }
    }
}
